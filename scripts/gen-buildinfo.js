// writes build/buildinfo.nsh from package.json (build.buildVersion) for the NSIS installer
const fs = require('fs'), path = require('path');
const pkg = require('../package.json');
const b = String(pkg.build.buildVersion);
fs.writeFileSync(path.join(__dirname, '..', 'build', 'buildinfo.nsh'), `; generated by scripts/gen-buildinfo.js - do not edit\n!define PW_BUILD "${b}"\n`);
console.log('buildinfo.nsh: ' + b);
