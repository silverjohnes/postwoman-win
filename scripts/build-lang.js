'use strict';
// Converts the macOS version's Resources/Localization/*.lproj/Localizable.strings (keys = English texts) into src/lang-mac.js.
// usage: node scripts/build-lang.js <path-to-mac>/Resources/Localization
const fs = require('fs'), path = require('path');
const dir = process.argv[2]; if (!dir) { console.error('usage: node scripts/build-lang.js <Localization dir>'); process.exit(1); }
const unesc = s => s.replace(/\\(["\\nt]|U[0-9a-fA-F]{4}|u[0-9a-fA-F]{4})/g, (m, c) => c === 'n' ? '\n' : c === 't' ? '\t' : c[0] === 'U' || c[0] === 'u' ? String.fromCharCode(parseInt(c.slice(1), 16)) : c);
const re = /^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;\s*$/;
const out = {};
for (const d of fs.readdirSync(dir).filter(x => x.endsWith('.lproj')).sort()) {
  const code = d.replace('.lproj', ''); if (code === 'en') continue; const m = {};
  for (const line of fs.readFileSync(path.join(dir, d, 'Localizable.strings'), 'utf8').split(/\r?\n/)) { const x = re.exec(line); if (x) m[unesc(x[1])] = unesc(x[2]); }
  out[code] = m;
}
const js = "'use strict';\n// Generated by scripts/build-lang.js from the macOS version's Localizable.strings (keys are the English texts).\n(function (root, data) { if (typeof module === 'object' && module.exports) module.exports = data; else root.LANG_MAC = data; })(typeof self !== 'undefined' ? self : this, " + JSON.stringify(out) + ");\n";
fs.writeFileSync(path.join(__dirname, '../src/lang-mac.js'), js);
console.log(Object.keys(out).length + ' languages, ' + Object.values(out).reduce((a, m) => a + Object.keys(m).length, 0) + ' strings');
